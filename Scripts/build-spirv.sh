#!/bin/sh
#
# build-spirv.sh
#
# Compiles every GLSL source under the Vulkan renderers' Shaders/ directories to
# SPIR-V and writes it out as a C header defining
#
#     static const uint32_t <name>_<stage>_spv[] = { ... };
#
# The generated headers are COMMITTED, so a normal build needs neither the
# Vulkan SDK nor glslc. Run this only when a .vert/.frag/.glsl changes:
#
#     VULKAN_SDK=~/VulkanSDK/1.4.350.1/macOS ./Scripts/build-spirv.sh
#
# glslc validates as it compiles: a shader that does not compile stops the
# script with its diagnostics. Each header is built into a temporary file and
# moved into place only once glslc has succeeded -- redirecting straight at the
# committed header would truncate it before glslc ran, so a failed compile would
# leave a header holding a guard and half a declaration, and the next build
# would fail on that wreckage instead of on the shader.
#

set -eu

SDK="${VULKAN_SDK:-$HOME/VulkanSDK/1.4.350.1/macOS}"
GLSLC="$SDK/bin/glslc"
SPIRV_DIS="$SDK/bin/spirv-dis"

if [ ! -x "$GLSLC" ]; then
	echo "build-spirv.sh: no glslc at $GLSLC" >&2
	echo "build-spirv.sh: set VULKAN_SDK to the SDK root (e.g. ~/VulkanSDK/1.4.350.1/macOS)" >&2
	exit 1
fi

if [ ! -x "$SPIRV_DIS" ]; then
	echo "build-spirv.sh: no spirv-dis at $SPIRV_DIS" >&2
	exit 1
fi

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DIRS="$ROOT/Src/Graphics/Vulkan/Shaders $ROOT/Src/Graphics/Vul3D/Shaders"

#
# Vul3D's renderers mirror every std140 uniform block in a C++ struct, and the
# two have to agree byte for byte. Rather than hand-type the offsets into the
# C++ -- a copy that passes exactly when both copies drift together -- they are
# read back OUT of the compiled SPIR-V here, into a generated header the .cpp
# files static_assert against. The GLSL is the source of truth.
#
# The read-back needs member names, which -O strips, so each shader is compiled
# a second time with -g -O0 purely to be disassembled; the committed .spv.h
# stays the optimised one.
#
OFFSETS_HEADER="$ROOT/Src/Graphics/Vul3D/Shaders/R3DBlockOffsets.h"
OFFSETS_RAW=$(mktemp -t vul3d-std140.XXXXXX)

# set -e aborts mid-shader on a glslc failure, so sweep the in-progress file up
# on the way out rather than leaving it beside the header it did not replace.
trap 'rm -f "$ROOT"/Src/Graphics/Vulkan/Shaders/*.spv.h.tmp "$ROOT"/Src/Graphics/Vul3D/Shaders/*.spv.h.tmp "$OFFSETS_HEADER.tmp" "$OFFSETS_RAW" "$OFFSETS_RAW.spv"' EXIT

count=0
for dir in $DIRS; do
	[ -d "$dir" ] || continue
	for source in "$dir"/*.vert "$dir"/*.frag; do
		[ -e "$source" ] || continue

		base=$(basename "$source")				# e.g. Shaders2D.frag
		ident=$(echo "$base" | tr '.-' '__')	# e.g. Shaders2D_frag
		guard=$(echo "$ident" | tr '[:lower:]' '[:upper:]')
		out="$dir/$base.spv.h"

		# -mfmt=c emits just the braced initialiser, so the header around it is
		# written here.
		{
			echo "// Generated by Scripts/build-spirv.sh from $base. Do not edit."
			echo "#ifndef INCLUDED_${guard}_SPV_H"
			echo "#define INCLUDED_${guard}_SPV_H"
			echo ""
			echo "#include <cstdint>"
			echo ""
			echo "static const uint32_t ${ident}_spv[] ="
			"$GLSLC" --target-env=vulkan1.0 -O -mfmt=c -I "$dir" -o - "$source"
			echo ";"
			echo ""
			echo "#endif	// INCLUDED_${guard}_SPV_H"
		} > "$out.tmp"
		mv "$out.tmp" "$out"

		# The std140 offsets, out of an unoptimised build of the same source.
		if [ "$dir" = "$ROOT/Src/Graphics/Vul3D/Shaders" ]; then
			"$GLSLC" --target-env=vulkan1.0 -g -O0 -I "$dir" -o "$OFFSETS_RAW.spv" "$source"
			"$SPIRV_DIS" "$OFFSETS_RAW.spv" | awk '
				$1 == "OpMemberName" { name = $4; gsub("\"", "", name); member[$2 "," $3] = name }
				$1 == "OpMemberDecorate" && $4 == "Offset" { offset[$2 "," $3] = $5 }
				END {
					for (key in offset) {
						if (key in member) {
							split(key, part, ",")
							block = substr(part[1], 2)
							printf "#define VUL3D_STD140_%s_%s %s\n", block, member[key], offset[key]
							if (offset[key] + 0 > last[block] + 0) { last[block] = offset[key] }
						}
					}
					# The offset of the FINAL member of each block. Assert
					# the last member of the C++ mirror against it and an
					# APPEND to the GLSL is caught: an append leaves every
					# existing offset alone, so the per-member asserts all
					# still pass while the mirror is silently short.
					for (block in last) {
						printf "#define VUL3D_STD140_%s_LASTOFFSET %s\n", block, last[block]
					}
				}' >> "$OFFSETS_RAW"
		fi

		echo "  $base -> $(basename "$out")"
		count=$((count + 1))
	done
done

#
# One #define per block member. A member that two shaders lay out DIFFERENTLY
# would appear twice with two values, which is a real defect (the descriptor set
# layout is one layout), so it is an error rather than a last-one-wins.
#
{
	echo "// Generated by Scripts/build-spirv.sh from the compiled SPIR-V. Do not edit."
	echo "//"
	echo "// The std140 byte offset of every uniform-block member the Vul3D shaders"
	echo "// declare. R3DShader.cpp and R3DScrollFog.cpp static_assert their C++ mirror"
	echo "// structs against these, so the GLSL is the one place a layout is decided."
	echo "#ifndef INCLUDED_R3DBLOCKOFFSETS_H"
	echo "#define INCLUDED_R3DBLOCKOFFSETS_H"
	echo ""
	sort -u "$OFFSETS_RAW"
	echo ""
	echo "#endif	// INCLUDED_R3DBLOCKOFFSETS_H"
} > "$OFFSETS_HEADER.tmp"

duplicates=$(sort -u "$OFFSETS_RAW" | awk '{ print $2 }' | sort | uniq -d)
if [ -n "$duplicates" ]; then
	echo "build-spirv.sh: these block members have two different std140 offsets:" >&2
	echo "$duplicates" >&2
	exit 1
fi

mv "$OFFSETS_HEADER.tmp" "$OFFSETS_HEADER"
echo "  std140 offsets -> $(basename "$OFFSETS_HEADER") ($(sort -u "$OFFSETS_RAW" | wc -l | tr -d ' ') members)"

echo "build-spirv.sh: $count shader(s) compiled."
