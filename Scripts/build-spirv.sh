#!/bin/sh
#
# build-spirv.sh
#
# Compiles every GLSL source under the Vulkan renderers' Shaders/ directories to
# SPIR-V and writes it out as a C header defining
#
#     static const uint32_t <name>_<stage>_spv[] = { ... };
#
# The generated headers are COMMITTED, so a normal build needs neither the
# Vulkan SDK nor glslc. Run this only when a .vert/.frag/.glsl changes:
#
#     VULKAN_SDK=~/VulkanSDK/1.4.350.1/macOS ./Scripts/build-spirv.sh
#
# glslc validates as it compiles: a shader that does not compile stops the
# script with its diagnostics. Each header is built into a temporary file and
# moved into place only once glslc has succeeded -- redirecting straight at the
# committed header would truncate it before glslc ran, so a failed compile would
# leave a header holding a guard and half a declaration, and the next build
# would fail on that wreckage instead of on the shader.
#

set -eu

SDK="${VULKAN_SDK:-$HOME/VulkanSDK/1.4.350.1/macOS}"
GLSLC="$SDK/bin/glslc"

if [ ! -x "$GLSLC" ]; then
	echo "build-spirv.sh: no glslc at $GLSLC" >&2
	echo "build-spirv.sh: set VULKAN_SDK to the SDK root (e.g. ~/VulkanSDK/1.4.350.1/macOS)" >&2
	exit 1
fi

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DIRS="$ROOT/Src/Graphics/Vulkan/Shaders $ROOT/Src/Graphics/Vul3D/Shaders"

# set -e aborts mid-shader on a glslc failure, so sweep the in-progress file up
# on the way out rather than leaving it beside the header it did not replace.
trap 'rm -f "$ROOT"/Src/Graphics/Vulkan/Shaders/*.spv.h.tmp "$ROOT"/Src/Graphics/Vul3D/Shaders/*.spv.h.tmp' EXIT

count=0
for dir in $DIRS; do
	[ -d "$dir" ] || continue
	for source in "$dir"/*.vert "$dir"/*.frag; do
		[ -e "$source" ] || continue

		base=$(basename "$source")				# e.g. Shaders2D.frag
		ident=$(echo "$base" | tr '.-' '__')	# e.g. Shaders2D_frag
		guard=$(echo "$ident" | tr '[:lower:]' '[:upper:]')
		out="$dir/$base.spv.h"

		# -mfmt=c emits just the braced initialiser, so the header around it is
		# written here.
		{
			echo "// Generated by Scripts/build-spirv.sh from $base. Do not edit."
			echo "#ifndef INCLUDED_${guard}_SPV_H"
			echo "#define INCLUDED_${guard}_SPV_H"
			echo ""
			echo "#include <cstdint>"
			echo ""
			echo "static const uint32_t ${ident}_spv[] ="
			"$GLSLC" --target-env=vulkan1.0 -O -mfmt=c -I "$dir" -o - "$source"
			echo ";"
			echo ""
			echo "#endif	// INCLUDED_${guard}_SPV_H"
		} > "$out.tmp"
		mv "$out.tmp" "$out"

		echo "  $base -> $(basename "$out")"
		count=$((count + 1))
	done
done

echo "build-spirv.sh: $count shader(s) compiled."
